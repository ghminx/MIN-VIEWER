import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdirSync} from 'node:fs';
import {createDevice,node} from './support/android-device.mjs';
import {selectDownload,escapePattern} from './support/document-picker.mjs';
const serial=process.env.MIN_TEST_DEVICE||'emulator-5554';
const d=createDevice({serial,physical:process.env.MIN_TEST_PHYSICAL==='1',dumpPath:'/sdcard/min-import-preview.xml',attempts:25});
const {run,wait,tap,screen}=d;
mkdirSync('.research/import-test',{recursive:true});
const source=`.research/import-test/preview-${Date.now()}.pdf`;
execFileSync('python',['-c',"import sys;sys.path.insert(0,'.research/py');import pymupdf as f;d=f.open();[d.new_page().insert_text((60,80),'IMPORT TEST '+str(i)) for i in range(1,3)];d.save(sys.argv[1])",source]);
await d.withRotation(0,async()=>{
 const name=`MIN-import-preview-${Date.now()}.pdf`;
 run('push',source,`/sdcard/Download/${name}`);
 run('shell','am','broadcast','-a','android.intent.action.MEDIA_SCANNER_SCAN_FILE','-d',`file:///sdcard/Download/${name}`);
 run('shell','am','force-stop','org.minviewer.app');run('shell','am','start','-W','-n','org.minviewer.app/.MainActivity');
 tap(await wait(/파일 열기/),'파일 열기');await selectDownload(d,name);
 const preview=await wait(/PDF 1쪽/);
 assert.ok(node(preview,'문서에 추가'),'외부 PDF 미리보기에서 문서에 추가 버튼 필요');
 assert.ok(!node(preview,'필기 시작'),'추가 전 미리보기에는 필기 도구가 없어야 함');
 tap(preview,'문서에 추가');
 await wait(/문서에 추가 완료|필기 시작/);
 run('shell','rm','--',`/sdcard/Download/${name}`);
 run('shell','am','force-stop','org.minviewer.app');run('shell','am','start','-W','-n','org.minviewer.app/.MainActivity');
 const library=await wait(new RegExp(escapePattern(name)));
 tap(library,escapePattern(name));await wait(/PDF 1쪽/);
 assert.ok(node(screen(),'필기 시작'),'보관 문서 재열기 후 필기 전환 필요');
 tap(screen(),'필기 시작');await wait(/읽기 모드로 전환/);
 run('shell','input','keyevent','BACK');
 let home=await wait(new RegExp(escapePattern(name)+' 관리'));
 const matches=[...home.matchAll(new RegExp('content-desc=\"'+escapePattern(name)+' 관리\"','g'))];
 assert.equal(matches.length,1,'필기 전환 후 하나의 문서 항목 유지');
 tap(home,escapePattern(name)+' 관리');let manage=await wait(/사본·필기 삭제/);
 tap(manage,'사본·필기 삭제');let confirm=await wait(/보관 사본과 필기를 삭제할까요/);tap(confirm,'사본·필기 삭제');
 tap(await wait(/필기 문서 삭제 완료/),'문서 관리 닫기');await wait(/최근 문서/);await new Promise(r=>setTimeout(r,1000));home=screen();
 assert.doesNotMatch(home,new RegExp(escapePattern(name)),'시험용 보관 항목 삭제');
 console.log('IMPORT_PREVIEW_REOPEN_INK_SINGLE_DELETE_PASS');
});
